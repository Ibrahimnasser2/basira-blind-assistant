# -*- coding: utf-8 -*-
"""Build BASIRA AI Arabic Word report."""
from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement


def set_rtl(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    pPr.append(bidi)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def set_run_arabic(run, size=12, bold=False, color=None):
    run.font.name = 'Arial'
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.append(rfonts)
    rfonts.set(qn('w:ascii'), 'Arial')
    rfonts.set(qn('w:hAnsi'), 'Arial')
    rfonts.set(qn('w:cs'), 'Arial')
    # ensure complex script size & bold
    sz = OxmlElement('w:szCs')
    sz.set(qn('w:val'), str(size * 2))
    rpr.append(sz)
    if bold:
        bcs = OxmlElement('w:bCs')
        rpr.append(bcs)
    rtl = OxmlElement('w:rtl')
    rpr.append(rtl)
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = color


def add_heading(doc, text, level=1, color=RGBColor(0x1F, 0x3A, 0x68)):
    p = doc.add_paragraph()
    set_rtl(p)
    sizes = {0: 22, 1: 18, 2: 14, 3: 12}
    r = p.add_run(text)
    set_run_arabic(r, size=sizes.get(level, 12), bold=True, color=color)
    return p


def add_para(doc, text, size=12, bold=False):
    p = doc.add_paragraph()
    set_rtl(p)
    r = p.add_run(text)
    set_run_arabic(r, size=size, bold=bold)
    return p


def add_bullet(doc, text, size=12, bold=False):
    p = doc.add_paragraph(style='List Bullet')
    set_rtl(p)
    r = p.add_run(text)
    set_run_arabic(r, size=size, bold=bold)
    return p


def add_separator(doc):
    p = doc.add_paragraph()
    set_rtl(p)
    r = p.add_run('―' * 30)
    set_run_arabic(r, size=12, color=RGBColor(0x99, 0x99, 0x99))


